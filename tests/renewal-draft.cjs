// Run from the repository root with Playwright installed. Set CHROME_PATH to use system Chrome.
const assert = require("node:assert/strict");
const { chromium } = require("playwright");
const { pathToFileURL } = require("node:url");
const path = require("node:path");

(async () => {
  const browser = await chromium.launch({executablePath: process.env.CHROME_PATH});
  try {
    const context = await browser.newContext();
    const page = await context.newPage();
    const errors = [];
    page.on("pageerror", err => errors.push(err.message));
    page.setDefaultTimeout(5000);
    const url = pathToFileURL(path.resolve("vercel-copy/site/index.html")).href;
    const open = () => page.goto(url);
    const rows = page.locator(".cost-line");
    const pdf = page.locator("#addendum-document");
    const discount = page.locator(".discount-line").last();
    const output = name => pdf.locator('[data-output="' + name + '"]').first().innerText();
    const fill = (id, value) => page.locator("#" + id).fill(value);
    const reload = () => page.reload();
    const click = id => page.locator("#" + id).click();
    const pdfText = () => pdf.innerText();
    async function edit(locator, text) {
      await locator.click();
      await page.keyboard.press("End");
      await page.keyboard.type(text);
    }
    const rowFor = name => rows.filter({has: page.locator('.line-product:has(option:checked[value="' + name + '"])')});
    const selected = "Additional 5 User Bundle";
    await open();
    assert.equal(await rows.count(),2);
    await fill("customer-name","Draft Customer");
    await fill("customer-signer-name","Test Signer");
    await fill("customer-signer-title","Director");
    await fill("agreement-date","January 1, 2026");
    await fill("renewal-end-date","January 1, 2027");
    await page.locator("#currency").selectOption("EUR");
    await rowFor("Additional User").locator(".line-product").selectOption(selected);
    const bundle = rowFor(selected);
    assert.equal(await bundle.locator(".line-new-quantity").inputValue(),"1");
    await bundle.locator(".line-renewal-mode").check();
    assert.equal(await page.locator("#renewed-users").inputValue(),"10");
    assert.match(await pdfText(),/30% discount/);
    await click("add-discount-line");
    assert.match(await pdfText(),/15% discount/);
    assert.equal(await pdf.getByText("Education / Non-profit Discount:",{exact:true}).count(),1);
    await click("toggle-overage-clause");
    const card = rowFor("Jotform Enterprise Base Package (includes 5 users)");
    await card.locator(".line-unit-price").fill("6000");
    await click("add-discount-line");
    await discount.locator(".discount-type").selectOption("custom");
    await discount.locator(".discount-custom-name").fill("Partner");
    await discount.locator(".discount-custom-rate").fill("10");
    assert.equal(await output("totalUsed"),"€6,029.10");
    await fill("total-used","6123.45");
    await edit(pdf.locator("p").first(), " EDITED INTRO");
    await edit(pdf.locator('li[data-pdf-key="term"]'), " EDITED TERM");
    await edit(pdf.locator(".cost-item-group dt").first(), " EDITED LABEL");
    await edit(pdf.locator('[data-output="customerName"]'), " CUSTOM");
    await reload();
    assert.equal(await output("totalUsed"),"€6,123.45");
    assert.equal(await page.locator("#customer-name").inputValue(),"Draft Customer");
    assert.match(await output("customerName"),/CUSTOM/);
    assert.equal(await card.locator(".line-unit-price").inputValue(),"6000");
    assert.equal(await discount.locator(".discount-custom-rate").inputValue(),"10");
    assert.equal(await page.locator("#toggle-overage-clause").getAttribute("aria-pressed"),"true");
    for (const text of ["EDITED INTRO","EDITED TERM","EDITED LABEL","Test Signer","Director","Partner"]) assert((await pdfText()).includes(text),text);
    await click("reset-total-override");
    assert.equal(await output("totalUsed"),"€6,029.10");
    await bundle.locator(".line-new-quantity").fill("0");
    assert.equal(await output("totalUsed"),"€3,780.00");
    assert.equal(await page.locator("#renewed-users").inputValue(),"5");
    assert.doesNotMatch(await pdfText(),/available only at the time of renewal/);
    assert.match(await pdfText(),/Number of 5-User Bundle/);
    await reload();
    assert.equal(await bundle.locator(".line-new-quantity").inputValue(),"0");
    assert.match(await pdfText(),/EDITED LABEL/);
    console.log("Passed: rates, counts, discounts, overrides, custom prices, currency, signers, clauses and PDF edits across reloads.");
    await click("add-cost-line-bottom");
    const blank = rows.filter({has:page.locator('.line-product:has(option:checked[value=""])')});
    assert.equal(await blank.locator(".money-input > span").innerText(),"€");
    await reload(); assert.equal(await blank.count(),1);
    await click("add-cost-line-bottom"); assert.equal(await rows.count(),3);
    const available = await blank.locator(".line-product option").evaluateAll(opts=>opts.map(o=>o.value).filter(Boolean));
    assert.equal(available.length,23);
    for (const product of available) {
      if (product !== available[0]) await click("add-cost-line-bottom");
      await blank.locator(".line-product").selectOption(product);
      const row = rowFor(product).last();
      if (await row.locator(".line-renewal-mode").isEnabled()) await row.locator(".line-renewal-mode").check();
    }
    const hipaa = rowFor("HIPAA / SOC2 Compliance");
    await hipaa.locator("summary").click();
    const forward = pdf.getByText("Conversion from Non-HIPAA Server to HIPAA-compliant Server.", {exact:true});
    const reverse = pdf.getByText("Conversion from HIPAA-compliant Server to Non-HIPAA Server.", {exact:true});
    assert.equal(await forward.count(),1);
    await hipaa.locator(".line-effect").selectOption("reduction");
    assert.equal(await forward.count(),0);
    assert.equal(await reverse.count(),1);
    await hipaa.locator(".line-renewal-mode").uncheck();
    assert.equal(await reverse.count(),0);
    await hipaa.locator(".line-renewal-mode").check();
    await hipaa.locator(".line-effect").selectOption("credit");
    await hipaa.locator(".line-credit-description").fill("HIPAA billing adjustment");
    assert.equal(await reverse.count(),0);
    assert.equal(await pdf.getByText("Customer will receive a service credit for HIPAA billing adjustment.", {exact:true}).count(),1);
    await hipaa.locator(".line-effect").selectOption("reduction");
    const service = rowFor("Professional Services");
    await service.locator("summary").click();
    await service.locator(".line-unit-price").fill("240");
    await service.locator(".line-basis").selectOption("back-charge");
    await service.locator(".line-back-charge-months").fill("3");
    await service.locator(".line-effect").selectOption("credit");
    await service.locator(".line-credit-description").fill("Unused service");
    await service.locator("summary").click();
    const domain = rowFor("Additional Custom Domain");
    await domain.locator("summary").click();
    await domain.locator(".line-effect").selectOption("reduction");
    await domain.locator(".line-waived").check();
    await page.waitForFunction(()=>document.querySelectorAll(".document-sheet").length>1);
    const snapshot=()=>pdf.evaluate(el=>el.innerText.replaceAll("[Continued on the next page]","").replace(/\s+/g," ").trim());
    const before=await snapshot();
    const total=await output("totalUsed");
    await reload(); await page.waitForFunction(()=>document.querySelectorAll(".document-sheet").length>1);
    assert.equal(await rows.count(),25);
    assert.equal(await snapshot(),before);
    assert.equal(await output("totalUsed"),total);
    assert.equal(await service.locator(".line-back-charge-months").inputValue(),"3");
    assert.equal(await service.locator("details").getAttribute("open"),null);
    assert(await domain.locator(".line-waived").isChecked());
    assert.match(before,/Customer will receive a service credit for Unused service/);
    assert.match(before,/A cost reduction for Additional Custom Domain/);
    assert((await page.pdf({format:"A4"})).length>10000);
    await domain.locator(".remove-cost-line").click();
    await reload();
    assert.equal(await domain.count(),0);
    console.log("Passed: all 23 catalog products, multi-page restoration, print generation, back charges, credits, waived reductions, card removal and unfinished rows.");
    page.once("dialog",d=>d.dismiss()); await click("reset-form"); assert.equal(await rows.count(),24);
    page.once("dialog",d=>d.accept()); await click("reset-document"); await reload();
    assert.doesNotMatch(await pdfText(),/EDITED INTRO|EDITED TERM|EDITED LABEL/);
    assert.equal(await rows.count(),24);
    await click("reset-form"); await reload();
    assert.equal(await rows.count(),2);assert.equal(await page.locator(".discount-line").count(),0);
    assert.equal(await page.locator("#customer-name").inputValue(),"");assert.equal(await output("totalUsed"),"$8,328.00");
    assert.equal(await page.evaluate(()=>sessionStorage.getItem("renewal-addendum-draft-v1")),null);
    await page.evaluate(()=>sessionStorage.setItem("renewal-addendum-draft-v1","{broken")); await reload();
    assert.equal(await rows.count(),2);
    await fill("customer-name","Last keystroke"); await reload();
    assert.equal(await page.locator("#customer-name").inputValue(),"Last keystroke");
    const second=await context.newPage();await second.goto(url);assert.equal(await second.locator("#customer-name").inputValue(),"");
    await page.evaluate(() => { window.print = () => { document.body.dataset.printed = "yes"; }; });
    await click("download-pdf");
    assert.equal(await page.locator("body").getAttribute("data-printed"),null);
    await fill("agreement-date","2026-01-01");
    await fill("renewal-end-date","2027-01-01");
    await click("download-pdf"); assert.equal(await page.locator("body").getAttribute("data-printed"),"yes");
    await page.evaluate(() => { delete document.body.dataset.printed; });
    await rowFor("Additional User").locator(".line-new-quantity").fill("-1");
    await click("download-pdf"); assert.equal(await page.locator("body").getAttribute("data-printed"),null);
    console.log("Passed: the Download PDF action invokes printing for valid entries and blocks missing dates and negative quantities.");
    const user = rowFor("Additional User");
    await user.locator(".line-new-quantity").fill("2");
    for (const [code, amount] of [["USD","$10,224.00"],["CAD","CA$15,332.00"],["GBP","£7,740.00"],["EUR","€8,980.00"],["AUD","A$15,828.00"]]) {
      await page.locator("#currency").selectOption(code);
      assert.equal(await output("totalUsed"),amount);
    }
    await page.locator("#currency").selectOption("USD");
    await fill("months-remaining","6");
    assert.equal(await output("totalUsed"),"$5,112.00");
    await fill("renewed-users","4");
    assert.equal(await user.locator(".line-effect").inputValue(),"reduction");
    assert.match(await pdfText(),/from 5 Permitted Users to 4 Permitted Users/);
    await reload(); assert.equal(await page.locator("#renewed-users").inputValue(),"4");
    assert.equal(await output("totalUsed"),"$3,690.00");
    await click("feedback-button");
    assert.equal(await page.locator("#feedback-modal iframe").getAttribute("src"),"https://form.jotform.com/262801722355959");
    await page.keyboard.press("Escape"); assert(await page.locator("#feedback-modal").isHidden());
    await click("agreement-date-picker-button"); assert(await page.locator("#agreement-date-calendar").isVisible());
    await click("calendar-today"); assert(await page.locator("#agreement-date-calendar").isHidden());
    await page.locator("#panel-resizer").focus(); await page.keyboard.press("ArrowRight");
    const width=await page.locator("#panel-resizer").getAttribute("aria-valuenow");
    await reload(); assert.equal(await page.locator("#panel-resizer").getAttribute("aria-valuenow"),width);
    console.log("Passed: currency conversion, prorating, user-count reductions, calendar picker, feedback link and panel resizing.");
    await fill("renewed-users",""); await reload();
    assert.equal(await page.locator("#renewed-users").inputValue(),"");
    assert.deepEqual(errors,[]);
    console.log("Passed: reset, cancel, PDF-only reset, immediate refresh, corrupt draft recovery, independent tabs and no uncaught page errors.");
  } finally { await browser.close(); }
})().catch(error=>{ console.error(error); process.exitCode=1; });
